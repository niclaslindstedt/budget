// Recursively widen every leaf from its literal type ("Save") to the
// plain `string` type. Without this, `sv.ts` would have to repeat
// every English string verbatim to satisfy `Catalog`, because each
// `as const` leaf would otherwise be its own one-string union.
type Widen<T> = T extends string
  ? string
  : T extends object
    ? { [K in keyof T]: Widen<T[K]> }
    : T;

export type Catalog = Widen<typeof en>;
